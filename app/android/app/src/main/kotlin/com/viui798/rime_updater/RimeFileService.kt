package com.viui798.rime_updater

import androidx.annotation.Keep
import android.os.ParcelFileDescriptor
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.MessageDigest
import java.util.UUID
import java.util.zip.ZipInputStream

/** Runs as shell through Shizuku. No shell command execution or private /data access. */
@Keep
class RimeFileService : IRimeFiles.Stub() {
    override fun destroy() { kotlin.system.exitProcess(0) }

    private fun root(path: String): File {
        require(Regex("/storage/emulated/0/Android/data/[A-Za-z0-9_.]+/files/.+").matches(path)) {
            "仅支持 Android/data 下的输入法用户目录"
        }
        val file = File(path)
        require(file.canonicalPath == path && file.isDirectory) { "目录不可访问：$path" }
        return file
    }
    private fun child(root: File, rel: String): File {
        require(rel.isNotEmpty() && !rel.startsWith('/') && rel.split('/').none { it == ".." || it == "." })
        val file = File(root, rel)
        require(file.canonicalPath == root.path + "/" + rel) { "不支持符号链接：$rel" }
        return file
    }
    private fun digest(file: File): String? {
        if (!file.exists()) return null
        require(file.isFile) { "路径不是普通文件：$file" }
        val md = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val buffer = ByteArray(65536)
            while (true) { val n = input.read(buffer); if (n < 0) break; md.update(buffer, 0, n) }
        }
        return md.digest().joinToString("") { "%02x".format(it) }
    }
    private fun looksLike(dir: File): Boolean = dir.listFiles()?.any {
        it.isFile && (it.name.endsWith(".schema.yaml") || it.name in listOf("installation.yaml", "default.yaml", "default.custom.yaml", "rime.lua"))
    } == true

    override fun inspect(path: String): String {
        val dir = root(path)
        val result = JSONObject().put("found", looksLike(dir))
        var version = File(dir, ".cheese-tiger-version").takeIf { it.isFile }?.readText()?.trim() ?: ""
        if (version.isEmpty()) File(dir, "CHANGELOG.md").takeIf { it.isFile }?.useLines { lines ->
            version = lines.firstOrNull { it.startsWith("## v") }?.substring(3)?.substringBefore('（')?.trim() ?: ""
        }
        result.put("version", version.removePrefix("v"))
        val backups = JSONArray()
        File(dir, ".cheese-tiger-backup").listFiles()?.filter { it.isDirectory && !it.name.startsWith('.') }?.sortedByDescending { it.name }?.forEach {
            val manifest = try { JSONObject(File(it, "manifest.json").readText()) } catch (_: Exception) { JSONObject() }
            backups.put(JSONObject().put("stamp", it.name).put("version", manifest.optString("version"))
                .put("previous", manifest.optString("previous_version"))
                .put("overwritten", manifest.optJSONArray("overwritten")?.length() ?: 0)
                .put("created", manifest.optJSONArray("created")?.length() ?: 0)
                .put("deleted", manifest.optJSONArray("deleted")?.length() ?: 0))
        }
        return result.put("backups", backups).toString()
    }
    override fun discoverRoots(path: String): String {
        val dir = root(path)
        val result = JSONArray()
        fun add(candidate: File) {
            if (!looksLike(candidate)) return
            try {
                val info = JSONObject(inspect(candidate.path))
                info.put("path", candidate.path)
                info.put("suffix", if (candidate == dir) "" else candidate.name)
                result.put(info)
            } catch (_: IllegalArgumentException) { /* Do not follow symlinked user directories. */ }
        }
        if (looksLike(dir)) add(dir) else {
            for (container in listOf(dir, File(dir, "schemas"))) {
                container.listFiles()?.filter { it.isDirectory && it.name !in setOf("build", "conf", "themes", "themes_disabled", "scripts", "logs", "sync") }?.sortedBy { it.name }?.forEach { add(it) }
            }
        }
        return result.toString()
    }
    override fun files(path: String): String {
        val dir = root(path)
        val result = JSONArray()
        fun scan(folder: File) {
            val entries = folder.listFiles() ?: error("无法读取目录：$folder")
            for (file in entries) {
                val rel = file.relativeTo(dir).invariantSeparatorsPath
                // Build output is regenerated by the input method, never staged or committed.
                // sync/ 是 Rime 自己的同步数据（个人数据），与 shouldCopy 的规则一致，不参与更新。
                if (rel == "build" || rel == "sync" || file.name.startsWith(".rime-updater-txn-")) continue
                child(dir, rel) // Reject links rather than silently following them.
                if (file.isDirectory) scan(file)
                else if (file.isFile) result.put(rel)
                require(result.length() <= 15000) { "文件过多，请清理旧备份后重试" }
            }
        }
        scan(dir)
        return result.toString()
    }
    override fun read(path: String, relative: String): ParcelFileDescriptor =
        ParcelFileDescriptor.open(child(root(path), relative), ParcelFileDescriptor.MODE_READ_ONLY)

    /** Bundle: manifest first, followed by changed files. Preflight all hashes; retain recovery on failed rollback. */
    @Synchronized override fun commit(path: String, bundle: ParcelFileDescriptor): String {
        val dir = root(path)
        check(dir.listFiles()?.none { it.name.startsWith(".rime-updater-txn-") } != false) {
            "发现未完成事务，请先检查用户目录中的 .rime-updater-txn-* 救援目录"
        }
        val txn = File(dir, ".rime-updater-txn-${UUID.randomUUID()}")
        check(txn.mkdir()) { "无法在目标目录创建事务，请检查 Shizuku 权限" }
        val fresh = File(txn, "new").apply { mkdir() }
        val old = File(txn, "old").apply { mkdir() }
        val applied = mutableListOf<String>()
        val committed = mutableMapOf<String, String?>()
        var originals = JSONObject()
        try {
            val manifest = ZipInputStream(ParcelFileDescriptor.AutoCloseInputStream(bundle)).use { zip ->
                check(zip.nextEntry?.name == "__manifest__.json") { "事务缺少清单" }
                val plan = JSONObject(zip.readBytes().toString(Charsets.UTF_8))
                originals = plan.getJSONObject("expected")
                val writes = plan.getJSONArray("writes")
                val names = (0 until writes.length()).map { writes.getString(it) }.toSet()
                require(names.all { originals.has(it) }) { "写入缺少预期哈希" }
                val extracted = mutableSetOf<String>()
                while (true) {
                    val entry = zip.nextEntry ?: break
                    require(!entry.isDirectory && entry.name in names && extracted.add(entry.name))
                    child(dir, entry.name)
                    val output = child(fresh, entry.name)
                    output.parentFile!!.mkdirs()
                    output.outputStream().use { zip.copyTo(it) }
                }
                check(extracted == names) { "事务文件不完整" }
                plan
            }
            val keys = originals.keys().asSequence().toList()
            for (rel in keys) {
                require(rel.split('/').none { it == "build" || it.startsWith(".rime-updater-txn-") })
                val expected = if (originals.isNull(rel)) null else originals.getString(rel)
                check(digest(child(dir, rel)) == expected) { "文件已被输入法修改，请重试：$rel" }
            }
            // Recovery copies are prepared for every affected file before the first write.
            for (rel in keys) {
                val file = child(dir, rel)
                if (file.isFile) { val backup = child(old, rel); backup.parentFile!!.mkdirs(); file.copyTo(backup) }
            }
            File(txn, "manifest.json").writeText(manifest.toString())
            val writes = manifest.getJSONArray("writes")
            val writeSet = (0 until writes.length()).map { writes.getString(it) }.toSet()
            for (rel in keys.sortedBy { if (it.startsWith(".cheese-tiger-backup/")) 0 else 1 }) {
                val dest = child(dir, rel)
                val expected = if (originals.isNull(rel)) null else originals.getString(rel)
                check(digest(dest) == expected) { "文件已改变，请重试：$rel" }
                val nextHash = if (rel in writeSet) digest(child(fresh, rel)) else null
                if (rel in writeSet) {
                    dest.parentFile!!.mkdirs()
                    check(child(fresh, rel).renameTo(dest)) { "写入失败：$rel" }
                } else if (dest.exists()) check(dest.delete()) { "删除失败：$rel" }
                applied.add(rel)
                committed[rel] = nextHash
            }
            // Remove empty parents left by deletions (e.g. cleared snapshot folders).
            for (rel in keys.filter { it !in writeSet }) {
                var parent = child(dir, rel).parentFile
                while (parent != null && parent != dir && parent.isDirectory && parent.list()?.isEmpty() == true) {
                    if (!parent.delete()) break
                    parent = parent.parentFile
                }
            }
            txn.deleteRecursively()
            return "ok"
        } catch (error: Exception) {
            var recovered = true
            for (rel in applied.asReversed()) {
                try {
                    val dest = child(dir, rel)
                    val saved = child(old, rel)
                    check(digest(dest) == committed[rel]) { "恢复前文件被其他进程修改：$rel" }
                    if (saved.isFile) { dest.parentFile!!.mkdirs(); saved.copyTo(dest, overwrite = true) }
                    else if (dest.exists()) check(dest.delete())
                } catch (_: Exception) { recovered = false }
            }
            if (recovered) txn.deleteRecursively()
            throw IllegalStateException("${error.message}" + if (recovered) "（未提交或已恢复）" else "；恢复失败，保留救援目录：${txn.path}")
        }
    }
}
